"""
storage/eval_store.py — Retrieval Evaluation Logger
=====================================================

Append-only JSONL logger that records every retrieval event.
One JSON object per line (JSONL format) so you can:
  - Stream-read the file without loading it all into memory
  - Append without rewriting the whole file
  - grep/jq for specific queries or courses

WHY LOG RETRIEVALS?
  Without data you're guessing whether hybrid search helps,
  whether multi-query improves results, or whether chunking
  changes are working. This log gives you the evidence.

WHAT TO DO WITH THE LOG:
  After 50-100 queries, analyse with the companion script:
    python -m app.rag.tools.analyse_eval

  Key metrics to track:
    - Hit@5: was the correct answer in top-5 results?
    - avg_latency_ms: how fast is retrieval?
    - top_sources: which files are most often retrieved?
    - zero_result_queries: queries that returned nothing
"""

import json
import logging
import threading
from datetime import datetime
from typing import Optional

from app.rag.config import EVAL_LOGGING_ENABLED, EVAL_LOG_FILE
from app.rag.models import RetrievedResult

logger = logging.getLogger("nexus.rag.eval_store")

_write_lock = threading.Lock()


def log_retrieval(
    query: str,
    course_id: str,
    query_variants: list[str],
    results: list[RetrievedResult],
    retrieval_latency_ms: float,
    strategy: str = "hybrid_multiquery",
) -> None:
    """
    Log one retrieval event to the JSONL file.

    Parameters:
      query               — original user query
      course_id           — which course was searched
      query_variants      — alternatives generated by multi-query
      results             — ranked retrieval results (top-5)
      retrieval_latency_ms— how long retrieval took (ms)
      strategy            — label for the retrieval strategy used
    """
    if not EVAL_LOGGING_ENABLED:
        return

    record = {
        "timestamp":            datetime.now().isoformat(),
        "query":                query,
        "course_id":            course_id,
        "strategy":             strategy,
        "query_variants":       query_variants,
        "retrieval_latency_ms": round(retrieval_latency_ms, 1),
        "num_results":          len(results),
        "results": [
            {
                "rank":            i + 1,
                "chunk_id":        r.retrieval_chunk.chunk_id,
                "source_filename": r.retrieval_chunk.source_filename,
                "section_heading": r.retrieval_chunk.section_heading,
                "page_number":     r.retrieval_chunk.page_number,
                "element_type":    r.retrieval_chunk.element_type,
                "vector_score":    round(r.vector_score, 4),
                "bm25_score":      round(r.bm25_score, 4),
                "combined_score":  round(r.combined_score, 4),
                "citation":        r.citation_label,
            }
            for i, r in enumerate(results)
        ],
        # Leave these blank — filled in manually during analysis
        "hit_at_5":    None,   # bool: did top-5 contain the answer?
        "notes":       "",     # any manual annotation
    }

    try:
        with _write_lock:
            with open(EVAL_LOG_FILE, "a", encoding="utf-8") as f:
                f.write(json.dumps(record) + "\n")
    except OSError as e:
        logger.warning(f"Could not write eval log: {e}")


def read_log(limit: Optional[int] = None) -> list[dict]:
    """
    Read the evaluation log, newest-first.
    Useful for quick inspection in a REPL or test script.
    """
    if not EVAL_LOG_FILE.exists():
        return []
    records = []
    with open(EVAL_LOG_FILE, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                try:
                    records.append(json.loads(line))
                except json.JSONDecodeError:
                    continue
    records.reverse()   # Newest first
    return records[:limit] if limit else records


def summarise_log() -> dict:
    """
    Quick summary statistics from the eval log.
    Call this after a batch of manual testing to see how the pipeline is doing.
    """
    records = read_log()
    if not records:
        return {"total": 0}

    latencies   = [r["retrieval_latency_ms"] for r in records]
    hit_records = [r for r in records if r.get("hit_at_5") is not None]
    hits        = [r for r in hit_records if r["hit_at_5"] is True]

    sources: dict[str, int] = {}
    for r in records:
        for res in r.get("results", []):
            fname = res.get("source_filename", "unknown")
            sources[fname] = sources.get(fname, 0) + 1

    return {
        "total_queries":       len(records),
        "avg_latency_ms":      round(sum(latencies) / len(latencies), 1),
        "max_latency_ms":      max(latencies),
        "min_latency_ms":      min(latencies),
        "hit_at_5_pct":        round(100 * len(hits) / len(hit_records), 1) if hit_records else None,
        "annotated_queries":   len(hit_records),
        "zero_result_queries": sum(1 for r in records if r["num_results"] == 0),
        "top_sources":         sorted(sources.items(), key=lambda x: x[1], reverse=True)[:5],
    }